/** نشانه‌های «ساختن» در متن ماموریت (فقط پشتیبان وقتی نوع ثبت نشده باشد) */
const PRACTICAL_RE = /بساز|طراحی کن|درست کن|ایجاد کن|بکش|اصلاح کن|بازطراحی کن|تهیه کن|پیاده|بنویس/;
/** نشانه‌های «خواندن و فهمیدن» */
const READING_RE = /بخوان|مطالعه|تماشا|ببین|یاد بگیر|پیدا کن|تحقیق|توضیح بده|مقایسه کن|تحلیل کن|بررسی کن|یادداشت کن/;

/** نوع هر ماموریت — از دادهٔ صریح و در نبود آن از متن */
export function missionKind(field: string, idx: number): MissionKind {
  const def = FIELDS[field];
  const explicit = def?.kinds?.[idx];
  if (explicit === "practical" || explicit === "reading") return explicit;
  const text = def?.missions[idx] || "";
  if (READING_RE.test(text) && !PRACTICAL_RE.test(text)) return "reading";
  return "practical";
}

