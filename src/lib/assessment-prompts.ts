const MARKER_BLOCK_RE =
  /\[\[ASSESSMENT_RESULT\]\]([\s\S]*?)\[\[\/ASSESSMENT_RESULT\]\]/;
const MARKER_OPEN_RE = /\[\[ASSESSMENT_RESULT\]\]/g;
const MARKER_CLOSE_RE = /\[\[\/ASSESSMENT_RESULT\]\]/g;

const DEFAULT_SCORE: Record<number, number> = { 1: 20, 2: 45, 3: 70, 4: 90 };

/** تبدیل ارقام فارسی/عربی به لاتین */
function toLatinDigits(s: string): string {
  return s
    .replace(/[۰-۹]/g, (d) => String("۰۱۲۳۴۵۶۷۸۹".indexOf(d)))
    .replace(/[٠-٩]/g, (d) => String("٠١٢٣٤٥٦٧٨٩".indexOf(d)));
}

/**
 * مارکر [[ASSESSMENT_RESULT]] را از متن پاسخ جدا می‌کند.
 * - مارکر سالم: JSON.parse محافظت‌شده + validate level ∈ 1..4 + clamp score
 * - مارکر خراب/ناقص: همیشه کامل از reply حذف می‌شود
 */
export function extractAssessmentResult(text: string): {
  reply: string;
  result: AssessmentResult | null;
} {
  if (!text) return { reply: "", result: null };
  let result: AssessmentResult | null = null;
  const m = text.match(MARKER_BLOCK_RE);
  if (m && m[1]) {
    try {
      const p = JSON.parse(m[1].trim()) as Record<string, unknown>;
      const level = Math.round(Number(p.level));
      const rawScore = Number(p.score);
      if (level >= 1 && level <= 4) {
        const score = Number.isFinite(rawScore)
          ? Math.max(0, Math.min(100, Math.round(rawScore)))
          : DEFAULT_SCORE[level];
        const confidence =
          typeof p.confidence === "string" && p.confidence.trim()
            ? p.confidence.trim()
            : "متوسط";
        result = { level, score, confidence };
      }
    } catch {
      /* مارکر خراب — نادیده گرفته می‌شود ولی از متن حذف می‌شود */
    }
  }
  // حذف کامل مارکر از reply حتی اگر خراب/ناقص بود
  const reply = text
    .replace(MARKER_BLOCK_RE, "")
    .replace(MARKER_OPEN_RE, "")
    .replace(MARKER_CLOSE_RE, "")
    .replace(/[ \t]+\n/g, "\n")
    .trim();
  return { reply, result };
}

const LEVEL_WORD_TO_NUM: Record<string, number> = {
  "پیشرفته": 4,
  "متوسط": 3,
  "پایه": 2,
  "مبتدی": 1,
};

/**
 * fallback سمت سرور: اگر مدل مارکر را نفرستاد ولی گزارش نهایی صادر شده بود،
 * سطح/امتیاز/اطمینان را از خود متن گزارش parse می‌کند.
 */
export function parseReportFallback(report: string): AssessmentResult | null {
  if (!report) return null;
  const t = toLatinDigits(report);
  const lines = t.split(/\r?\n/);
  let level = 0;

  // ۱) صریح: "Level 3" یا "سطح ۳"
  const lm = t.match(/Level\s*([1-4])/i) || t.match(/سطح\s*([1-4])\s*[:：ـ]/);
  if (lm) level = Number(lm[1]);

  // ۲) واژهٔ سطح در خط حاوی «سطح نهایی» / «سطح کلی» / «سطح مهارت» / شروع‌کنندهٔ «سطح»
  const pickWord = (l: string): number => {
    for (const w of Object.keys(LEVEL_WORD_TO_NUM)) {
      if (l.includes(w)) return LEVEL_WORD_TO_NUM[w];
    }
    return 0;
  };
  if (!level) {
    for (const l of lines) {
      if (/سطح\s*(نهایی|کلی)/.test(l)) {
        const v = pickWord(l);
        if (v) {
          level = v;
          break;
        }
      }
    }
  }
  if (!level) {
    for (const l of lines) {
      const s = l.trim();
      if (/^[-*•]?\s*سطح/.test(s) && !/تخصصی|مهارت|جداگانه/.test(s)) {
        const v = pickWord(s);
        if (v) {
          level = v;
          break;
        }
      }
    }
  }
  if (!level) return null;

  // ۳) امتیاز: عدد بعد از «امتیاز» (تا ۳۰ نویسه فاصله)
  let score = NaN;
  const sm = t.match(/امتیاز[^0-9]{0,30}([0-9]{1,3})/);
  if (sm) score = Number(sm[1]);
  if (!Number.isFinite(score) || score < 0 || score > 100)
    score = DEFAULT_SCORE[level];

  // ۴) اطمینان: واژه در نزدیکی «اطمینان»
  let confidence = "متوسط";
  const ci = t.indexOf("اطمینان");
  if (ci >= 0) {
    const scope = t.slice(ci, ci + 120);
    if (scope.includes("بالا")) confidence = "بالا";
    else if (scope.includes("کم")) confidence = "کم";
    else if (scope.includes("متوسط")) confidence = "متوسط";
  }

  return {
    level,
    score: Math.max(0, Math.min(100, Math.round(score))),
    confidence,
  };
}

/* =========================================================
   پارس سؤال چهارگزینه‌ای از پیام مدل (سمت کلاینت)
   قالب اجباری:
     [متن مقدماتی/بازخورد]
     سؤال: متن سؤال
     الف) ...
     ب) ...
     ج) ...
     د) ...
   ========================================================= */

export interface McqQuestion {
  /** متنِ قبل از خط «سؤال:» (بازخورد پاسخ قبل یا سناریو) */
  intro: string;
  /** متن خود سؤال */
  question: string;
  /** چهار گزینه بدون برچسب */
  options: string[];
}

const MCQ_LABELS = ["الف", "ب", "ج", "د"];

function lineLabel(l: string): string | null {
  const m = l.match(/^(الف|ب|ج|د)\s*[\)\]]/);
  return m ? m[1] : null;
}

/**
 * اگر پیام دستیار در قالب سؤال چهارگزینه‌ای باشد، آن را می‌کاود؛
 * وگرنه null (و پیام به‌صورت متن ساده نمایش داده می‌شود).
 * دو حالت پشتیبانی می‌شود:
 *  ۱) سخت‌گیرانه: خط «سؤال:» + چهار گزینه
 *  ۲) شل: بدون خط «سؤال:» — دنبالهٔ ۴ گزینه و پاراگرافِ بالای آن به‌عنوان سؤال
 * در هر دو، آخرین بلاک پیام ملاک است (بازخورد قبلش می‌آید).
 */
export function parseMcqQuestion(raw: string): McqQuestion | null {
  return parseMcqStrict(raw) || parseMcqLoose(raw);
}

function cleanLines(raw: string): string[] {
  return raw
    .split(/\r?\n/)
    .map((l) => l.replace(/\*\*/g, "").replace(/^[-*•>\s]+/, "").trim());
}

function parseMcqStrict(raw: string): McqQuestion | null {
  const lines = cleanLines(raw);
  let qIdx = -1;
  for (let i = lines.length - 1; i >= 0; i--) {
    if (/^سؤال\s*[:：]/.test(lines[i])) {
      qIdx = i;
      break;
    }
  }
  if (qIdx < 0) return null;

  const optIdx: number[] = [];
  let from = qIdx + 1;
  for (const lab of MCQ_LABELS) {
    let found = -1;
    for (let i = from; i < lines.length; i++) {
      if (lineLabel(lines[i]) === lab) {
        found = i;
        break;
      }
      // اگر خط سؤال دیگری بین گزینه‌ها آمد، قالب شکسته است
      if (/^سؤال\s*[:：]/.test(lines[i])) return null;
    }
    if (found < 0) return null;
    optIdx.push(found);
    from = found + 1;
  }

  const options = optIdx.map((i) =>
    lines[i].replace(/^(الف|ب|ج|د)\s*[\)\]]\s*/, "").trim()
  );
  if (options.some((o) => !o)) return null;

  const qHead = lines[qIdx].replace(/^سؤال\s*[:：]\s*/, "").trim();
  const qBody = lines
    .slice(qIdx + 1, optIdx[0])
    .filter((l) => !lineLabel(l))
    .join("\n")
    .trim();
  const question = [qHead, qBody].filter(Boolean).join("\n");
  if (!question) return null;

  const intro = lines.slice(0, qIdx).join("\n").trim();
  return { intro, question, options };
}

function parseMcqLoose(raw: string): McqQuestion | null {
  const lines = cleanLines(raw);

  // آخرین خط گزینهٔ «الف»
  let aIdx = -1;
  for (let i = lines.length - 1; i >= 0; i--) {
    if (lineLabel(lines[i]) === "الف") {
      aIdx = i;
      break;
    }
  }
  if (aIdx < 0) return null;

  // ب/ج/د باید بلافاصله (حداکثر با یک خط فاصله) بعد از قبلی بیایند
  const optIdx = [aIdx];
  let from = aIdx + 1;
  for (const lab of MCQ_LABELS.slice(1)) {
    let found = -1;
    for (let i = from; i < Math.min(from + 3, lines.length); i++) {
      if (lineLabel(lines[i]) === lab) {
        found = i;
        break;
      }
    }
    if (found < 0) return null;
    optIdx.push(found);
    from = found + 1;
  }

  const options = optIdx.map((i) =>
    lines[i].replace(/^(الف|ب|ج|د)\s*[\)\]]\s*/, "").trim()
  );
  if (options.some((o) => !o)) return null;

  // سؤال = پاراگرافِ درست بالای گزینهٔ الف (یک خط خالی مجاز بینشان)
  let boundary = aIdx - 1;
  if (boundary >= 0 && lines[boundary] === "") boundary--;
  let s = boundary;
  while (s >= 0 && lines[s] !== "") s--;
  const question = lines.slice(s + 1, aIdx).join("\n").trim();
  if (!question) return null;

  const intro = lines.slice(0, s + 1).join("\n").trim();
  return { intro, question, options };
}
